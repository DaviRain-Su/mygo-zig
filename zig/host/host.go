// SetError records the latest host error for HostOpLastError.
func SetError(err error) {
	lastErrMu.Lock()
	if err == nil {
		lastErr = ""
	} else {
		lastErr = err.Error()
	}
	lastErrMu.Unlock()
}

type tsMethodEntry struct {
	service string
	method  string
	params  string // e.g. "arg0: string, arg1: number"
	callArg string // e.g. ", arg0, arg1"
	retType string // e.g. "{ message: string }"
}

type tsEventEntry struct {
	name    string
	payload string
}

var (
	tsMu      sync.Mutex
	tsMethods []tsMethodEntry
	tsEvents  []tsEventEntry
)

// CTSSpec passes comptime-synthesized TypeScript metadata from Zig.
type CTSSpec struct {
	Kind    uint32 // 1 = method, 2 = event
	_       uint32
	Service CStr
	Name    CStr
	Params  CStr
	CallArg CStr
	TypeStr CStr
}

func renderTypeScriptClient() []byte {
	tsMu.Lock()
	methods := slices.Clone(tsMethods)
	events := slices.Clone(tsEvents)
	tsMu.Unlock()
	if len(methods) == 0 && len(events) == 0 {
		return nil
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by `mygo generate`. DO NOT EDIT.\n\n")
	var imports []string
	if len(methods) > 0 {
		imports = append(imports, "call")
	}
	if len(events) > 0 {
		imports = append(imports, "event")
	}
	fmt.Fprintf(&out, "import { %s } from \"mygo-runtime\";\n", strings.Join(imports, ", "))

	var svcOrder []string
	bySvc := map[string][]tsMethodEntry{}
	for _, m := range methods {
		if _, ok := bySvc[m.service]; !ok {
			svcOrder = append(svcOrder, m.service)
		}
		bySvc[m.service] = append(bySvc[m.service], m)
	}
	for _, svc := range svcOrder {
		fmt.Fprintf(&out, "\nexport const %s = {\n", svc)
		for _, m := range bySvc[svc] {
			fmt.Fprintf(&out, "  %s(%s): Promise<%s> {\n", m.method, m.params, m.retType)
			fmt.Fprintf(&out, "    return call(%q%s);\n", svc+"."+m.method, m.callArg)
			out.WriteString("  },\n")
		}
		out.WriteString("} as const;\n")
	}

	if len(events) > 0 {
		out.WriteString("\nexport const events = {\n")
		for _, ev := range events {
			fmt.Fprintf(&out, "  %q: event<%s>(%q),\n", ev.name, ev.payload, ev.name)
		}
		out.WriteString("} as const;\n")
	}
	return out.Bytes()
}

func writeGeneratedClient(outPath string) error {
	src := renderTypeScriptClient()
	if len(src) == 0 {
		return nil
	}
	if old, err := os.ReadFile(outPath); err == nil && bytes.Equal(old, src) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(outPath, src, 0o644)
}

// Main runs the Zig library named libName and logs fatal errors.
func Main(libName string) {
	if err := Run(libName); err != nil {
		log.Fatal(err)
	}
}

// Run loads the Zig dynamic library named libName, initializes its bindings,
// handles MYGO_GENERATE when set, and runs the native MyGo event loop.
func Run(libName string) error {
	if !supported {
		return fmt.Errorf("zighost: unsupported platform %s/%s", runtime.GOOS, runtime.GOARCH)
	}
	libPath, err := findLibrary(libName)
	if err != nil {
		return err
	}
	handle, err := openLibrary(libPath)
	if err != nil {
		return fmt.Errorf("zighost: open %s: %w", libPath, err)
	}
	entry, err := librarySymbol(handle, "mygo_zig_entry")
	if err != nil {
		return fmt.Errorf("zighost: symbol mygo_zig_entry in %s: %w", libPath, err)
	}

	activeCall = func(kind, a0, a1, a2, a3 uintptr) uintptr {
		return callZig(entry, kind, a0, a1, a2, a3)
	}

	callbackOnce.Do(func() {
		callbackPtr = newHostCallback(hostDispatch)
	})

	if rc := int32(activeCall(ZigEventInit, callbackPtr, 0, 0, 0)); rc != 0 {
		lastErrMu.Lock()
		msg := lastErr
		lastErrMu.Unlock()
		if msg == "" {
			msg = fmt.Sprintf("Zig init failed with code %d", rc)
		}
		return errors.New(msg)
	}

	if out := os.Getenv("MYGO_GENERATE"); out != "" {
		return writeGeneratedClient(out)
	}

	mygo.App.WhenReady(func() {
		activeCall(ZigEventReady, 0, 0, 0, 0)
	})
	return mygo.App.Run()
}

func libFileName(name string) string {
	switch runtime.GOOS {
	case "darwin":
		return "lib" + name + ".dylib"
	case "windows":
		return name + ".dll"
	default:
		return "lib" + name + ".so"
	}
}

func findLibrary(name string) (string, error) {
	if env := os.Getenv("MYGO_ZIG_LIB"); env != "" {
		if _, err := os.Stat(env); err == nil {
			return env, nil
		}
		return "", fmt.Errorf("zighost: MYGO_ZIG_LIB=%q not found", env)
	}
	file := libFileName(name)
	var candidates []string
	if res, err := mygo.App.Path(mygo.PathResources); err == nil && res != "" {
		candidates = append(candidates,
			filepath.Join(res, file),
			filepath.Join(res, runtime.GOOS+"-"+runtime.GOARCH, file),
			filepath.Join(res, runtime.GOOS, file),
		)
	}
	if exe, err := os.Executable(); err == nil {
		candidates = append(candidates, filepath.Join(filepath.Dir(exe), file))
	}
	candidates = append(candidates,
		filepath.Join("resources", file),
		filepath.Join("resources", runtime.GOOS+"-"+runtime.GOARCH, file),
		filepath.Join("resources", runtime.GOOS, file),
		filepath.Join("zig-out", "lib", file),
		filepath.Join("zig-out", "bin", file),
		filepath.Join("zig", "zig-out", "lib", file),
		filepath.Join("zig", "zig-out", "bin", file),
	)
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			abs, err := filepath.Abs(c)
			if err == nil {
				return abs, nil
			}
			return c, nil
		}
	}
	return "", fmt.Errorf("zighost: could not find %s (checked MYGO_ZIG_LIB, resources/, and zig-out/)", file)
}

// ParseWindowOptions converts CWindowOptions into mygo.WindowOptions.
func ParseWindowOptions(raw *CWindowOptions) mygo.WindowOptions {
	if raw == nil {
		return mygo.WindowOptions{}
	}
	opts := mygo.WindowOptions{
		Title:           StrField(raw.Title),
		URL:             StrField(raw.URL),
		BackgroundColor: StrField(raw.BackgroundColor),
		Width:           int(raw.Width),
		Height:          int(raw.Height),
		MinWidth:        int(raw.MinWidth),
		MinHeight:       int(raw.MinHeight),
		MaxWidth:        int(raw.MaxWidth),
		MaxHeight:       int(raw.MaxHeight),
		UseContentSize:  raw.UseContentSize != 0,
		Hidden:          raw.Hidden != 0,
		Frameless:       raw.Frameless != 0,
		DisableResize:   raw.DisableResize != 0,
		AlwaysOnTop:     raw.AlwaysOnTop != 0,
		Transparent:     raw.Transparent != 0,
		Vibrancy:        mygo.Vibrancy(StrField(raw.Vibrancy)),
		VibrancyTint:    StrField(raw.VibrancyTint),
		TitleBarStyle:   mygo.TitleBarStyle(StrField(raw.TitleBarStyle)),
		TitleBarHeight:  int(raw.TitleBarHeight),
		Page: mygo.PageOptions{
			DevTools: mygo.DevTools(raw.DevTools),
		},
	}
	if name := StrField(raw.SessionName); name != "" {
		opts.Page.Session = mygo.NewSession(name)
	}
	opts.StateKey = StrField(raw.StateKey)
	return opts
}

type replyState struct {
	mu       sync.Mutex
	deferred bool
	done     bool
	out      []byte
	err      error
	ch       chan struct{}
}

var (
	nextReplyID atomic.Uintptr
	repliesMu   sync.Mutex
	replies     = map[uintptr]*replyState{}
)

func putReply(st *replyState) uintptr {
	id := nextReplyID.Add(1)
	if id == 0 {
		id = nextReplyID.Add(1)
	}
	repliesMu.Lock()
	replies[id] = st
	repliesMu.Unlock()
	return id
}

func getReply(id uintptr) *replyState {
	repliesMu.Lock()
	st := replies[id]
	repliesMu.Unlock()
	return st
}

func takeReply(id uintptr) *replyState {
	repliesMu.Lock()
	st := replies[id]
	delete(replies, id)
	repliesMu.Unlock()
	return st
}

