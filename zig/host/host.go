func windowOnEvent(winID int, kind int32, cbID uintptr) uintptr {
	w := mygo.WindowByID(winID)
	if w == nil {
		SetError(errors.New("mygo: window not found"))
		return ^uintptr(0)
	}
	fire := func(payload []byte) uintptr {
		ptr, n := SliceAddr(payload)
		return activeCall(ZigEventWindow, cbID, uintptr(winID), ptr, n)
	}
	switch kind {
	case 1: // close
		w.OnClose(func(e *mygo.CloseEvent) {
			if fire(nil) != 0 {
				e.PreventDefault()
			}
		})
	case 2:
		w.OnClosed(func() { fire(nil) })
	case 3:
		w.OnFocus(func() { fire(nil) })
	case 4:
		w.OnBlur(func() { fire(nil) })
	case 5:
		w.OnResize(func() {
			b := w.Bounds()
			raw, _ := json.Marshal(struct {
				Width  int `json:"width"`
				Height int `json:"height"`
			}{b.Width, b.Height})
			fire(raw)
		})
	case 6:
		w.OnFileDrop(func(e *mygo.FileDropEvent) {
			raw, _ := json.Marshal(e)
			fire(raw)
		})
	case 7:
		w.OnMove(func() {
			b := w.Bounds()
			raw, _ := json.Marshal(struct{ X, Y, Width, Height int }{b.X, b.Y, b.Width, b.Height})
			fire(raw)
		})
	case 8:
		w.OnShow(func() { fire(nil) })
	case 9:
		w.OnHide(func() { fire(nil) })
	case 10:
		w.OnMinimize(func() { fire(nil) })
	case 11:
		w.OnRestore(func() { fire(nil) })
	case 12:
		w.OnMaximize(func() { fire(nil) })
	case 13:
		w.OnUnmaximize(func() { fire(nil) })
	case 14:
		w.OnEnterFullScreen(func() { fire(nil) })
	case 15:
		w.OnLeaveFullScreen(func() { fire(nil) })
	case 16:
		w.OnReadyToShow(func() { fire(nil) })
	default:
		return ^uintptr(0)
	}
	return 0
}

type menuSpecItem struct {
	ID          string         `json:"id"`
	Label       string         `json:"label"`
	Type        string         `json:"type"`
	Role        string         `json:"role"`
	Accelerator string         `json:"accelerator"`
	Disabled    bool           `json:"disabled"`
	Hidden      bool           `json:"hidden"`
	Checked     bool           `json:"checked"`
	Submenu     []menuSpecItem `json:"submenu"`
}

func setAppMenu(raw []byte, cbID uintptr) uintptr {
	var spec []menuSpecItem
	if err := json.Unmarshal(raw, &spec); err != nil {
		SetError(err)
		return ^uintptr(0)
	}
	var convert func(items []menuSpecItem) []*mygo.MenuItem
	convert = func(items []menuSpecItem) []*mygo.MenuItem {
		out := make([]*mygo.MenuItem, len(items))
		for i, it := range items {
			mi := &mygo.MenuItem{
				ID:          it.ID,
				Label:       it.Label,
				Type:        mygo.MenuItemType(it.Type),
				Role:        mygo.MenuRole(it.Role),
				Accelerator: it.Accelerator,
				Disabled:    it.Disabled,
				Hidden:      it.Hidden,
				Checked:     it.Checked,
				Submenu:     convert(it.Submenu),
			}
			if cbID != 0 && mi.Role == "" && len(mi.Submenu) == 0 && mi.Type != mygo.MenuItemSeparator {
				idCopy := mi.ID
				if idCopy == "" {
					idCopy = mi.Label
				}
				mi.Click = func(_ *mygo.MenuItem, win *mygo.Window) {
					var wid uintptr
					if win != nil {
						wid = uintptr(win.ID())
					}
					idBytes := []byte(idCopy)
					ptr, n := SliceAddr(idBytes)
					activeCall(ZigEventMenu, cbID, wid, ptr, n)
				}
			}
			out[i] = mi
		}
		return out
	}
	mygo.App.SetMenu(mygo.NewMenu(convert(spec)))
	return 0
}

