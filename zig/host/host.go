		authReqsMu.Unlock()
		defer func() {
			authReqsMu.Lock()
			delete(authReqs, reqID)
			authReqsMu.Unlock()
		}()

		hostB := []byte(req.Host)
		realmB := []byte(req.Realm)
		schemeB := []byte(req.Scheme)
