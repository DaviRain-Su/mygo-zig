func WriteStringToOut(s string, outPtr, outCap uintptr) uintptr {
	return writeStringToOut(s, outPtr, outCap)
}

// WriteBytesToOut copies bytes into a Zig out buffer for opt-in host packages.
func WriteBytesToOut(b []byte, outPtr, outCap uintptr) uintptr {
	return writeBytesToOut(b, outPtr, outCap)
}

// PtrOf returns the address of p for activeCall payload args.
func PtrOf[T any](p *T) uintptr {
	return uintptrSlicePtr(p)
}

func writeBytesToOut(b []byte, outPtr, outCap uintptr) uintptr {
	if outPtr != 0 && outCap > 0 && len(b) > 0 {
		n := min(len(b), int(outCap))
		copy(BytesView(outPtr, uintptr(n)), b[:n])
	}
	return uintptr(len(b))
}

func writeNULPaths(paths []string, outPtr, outCap uintptr) uintptr {
	if len(paths) == 0 {
		return 0
	}
	var buf []byte
	for i, p := range paths {
		if i > 0 {
			buf = append(buf, 0)
		}
		buf = append(buf, p...)
	}
	return writeBytesToOut(buf, outPtr, outCap)
}

var (
	trayMu   sync.Mutex
	trays            = map[uintptr]*traySlot{}
	nextTray uintptr = 1
)

type traySlot struct {
	tray     *mygo.Tray
	menuCB   uintptr
	clickCB  uintptr
	rightCB  uintptr
	appearCB uintptr
}

func hostTray(sub, a1, a2, a3 uintptr) uintptr {
	switch sub {
	case TrayNew:
		spec := PtrTo[CTrayNewSpec](a1)
		if spec == nil {
			SetError(errors.New("zighost: tray new needs spec"))
			return 0
		}
		opts := mygo.TrayOptions{
			ID:             CopyString(spec.IDPtr, spec.IDLen),
			Icon:           CopyBytes(spec.IconPtr, spec.IconLen),
			IconIsTemplate: spec.Template != 0,
			Title:          CopyString(spec.TitlePtr, spec.TitleLen),
			ToolTip:        CopyString(spec.TipPtr, spec.TipLen),
		}
		menuCB := spec.MenuCbID
		tr, err := mygo.NewTray(opts)
		if err != nil {
			SetError(err)
			return 0
		}
		SetError(nil)
		trayMu.Lock()
		id := nextTray
		nextTray++
		slot := &traySlot{tray: tr, menuCB: menuCB}
		trays[id] = slot
		trayMu.Unlock()
		if spec.MenuLen > 0 {
			m, err := menuFromJSON(CopyBytes(spec.MenuJSONPtr, spec.MenuLen), menuCB, id)
			if err != nil {
				SetError(err)
				tr.Destroy()
				trayMu.Lock()
				delete(trays, id)
				trayMu.Unlock()
				return 0
			}
			tr.SetMenu(m)
		}
		return id

	case TrayDestroy:
		trayMu.Lock()
		slot := trays[a1]
		delete(trays, a1)
		trayMu.Unlock()
		if slot != nil && slot.tray != nil {
			slot.tray.Destroy()
		}
		return 0

	case TraySetIcon:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		spec := PtrTo[CTrayIconSpec](a2)
		if spec == nil {
			SetError(errors.New("zighost: tray setIcon needs spec"))
			return ^uintptr(0)
		}
		if err := slot.tray.SetIcon(CopyBytes(spec.PNGPtr, spec.PNGLen), spec.Template != 0); err != nil {
			SetError(err)
			return ^uintptr(0)
		}
		SetError(nil)
		return 0

	case TraySetTitle:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		slot.tray.SetTitle(CopyString(a2, a3))
		return 0

	case TraySetToolTip:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		slot.tray.SetToolTip(CopyString(a2, a3))
		return 0

	case TraySetMenu:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		if a2 == 0 || a3 == 0 {
			slot.tray.SetMenu(nil)
			return 0
		}
		// Optional: a0 packing can't carry menu cb; keep slot.menuCB from New, or accept menuCB in unused high — pass menuCB as... we use tray's stored menuCB.
		m, err := menuFromJSON(CopyBytes(a2, a3), slot.menuCB, a1)
		if err != nil {
			SetError(err)
			return ^uintptr(0)
		}
		slot.tray.SetMenu(m)
		SetError(nil)
		return 0

	case TrayPopUpMenu:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		slot.tray.PopUpMenu()
		return 0

	case TrayBounds:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		if out := PtrTo[CBounds](a2); out != nil {
			b := slot.tray.Bounds()
			*out = CBounds{X: int32(b.X), Y: int32(b.Y), Width: int32(b.Width), Height: int32(b.Height)}
		}
		return 0

	case TrayDark:
		slot := getTray(a1)
		if slot == nil {
			return 0
		}
		if slot.tray.Dark() {
			return 1
		}
		return 0

	case TrayOnEvent:
		slot := getTray(a1)
		if slot == nil {
			return ^uintptr(0)
		}
		cbID := a3
		switch a2 {
		case 1: // click
			slot.clickCB = cbID
			slot.tray.OnClick(func() {
				activeCall(ZigEventTray, cbID, a1, 1, 0)
			})
		case 2: // right
			slot.rightCB = cbID
			slot.tray.OnRightClick(func() {
				activeCall(ZigEventTray, cbID, a1, 2, 0)
			})
		case 3: // appearance
			slot.appearCB = cbID
			slot.tray.OnAppearanceChange(func() {
				activeCall(ZigEventTray, cbID, a1, 3, 0)
			})
		default:
			return ^uintptr(0)
		}
		return 0
	default:
		SetError(errors.New("zighost: unknown tray subop"))
		return ^uintptr(0)
	}
}

func getTray(id uintptr) *traySlot {
	trayMu.Lock()
	defer trayMu.Unlock()
	slot := trays[id]
	if slot == nil || slot.tray == nil {
		SetError(errors.New("zighost: tray not found"))
		return nil
	}
	return slot
}

func menuFromJSON(raw []byte, cbID, trayID uintptr) (*mygo.Menu, error) {
	var spec []menuSpecItem
	if err := json.Unmarshal(raw, &spec); err != nil {
		return nil, err
	}
	var convert func(items []menuSpecItem) []*mygo.MenuItem
	convert = func(items []menuSpecItem) []*mygo.MenuItem {
		out := make([]*mygo.MenuItem, len(items))
		for i, it := range items {
			mi := &mygo.MenuItem{
				ID:          it.ID,
				Label:       it.Label,
				Type:        mygo.MenuItemType(it.Type),
				Role:        mygo.MenuRole(it.Role),
				Accelerator: it.Accelerator,
				Disabled:    it.Disabled,
				Hidden:      it.Hidden,
				Checked:     it.Checked,
				Submenu:     convert(it.Submenu),
			}
			if cbID != 0 && mi.Role == "" && len(mi.Submenu) == 0 && mi.Type != mygo.MenuItemSeparator {
				idCopy := mi.ID
				if idCopy == "" {
					idCopy = mi.Label
				}
				mi.Click = func(_ *mygo.MenuItem, win *mygo.Window) {
					_ = win
					idBytes := []byte(idCopy)
					cs := CStr{Data: 0, Len: 0}
					ptr, n := SliceAddr(idBytes)
					cs.Data, cs.Len = ptr, n
					activeCall(ZigEventTray, cbID, trayID, 4, uintptrSlicePtr(&cs))
				}
			}
			out[i] = mi
		}
		return out
	}
	return mygo.NewMenu(convert(spec)), nil
}

// TrayByID returns the live *mygo.Tray for a Zig tray id, or nil.
func TrayByID(id uintptr) *mygo.Tray {
	trayMu.Lock()
	defer trayMu.Unlock()
	if slot := trays[id]; slot != nil {
		return slot.tray
	}
	return nil
}

// parseDialogFilters unpacks the Zig multi-filter blob, or falls back to a
// single name/ext pair. Blob layout: u8 count, then for each filter:
// u16le name_len + name, u16le ext_csv_len + ext_csv, u16le mime_csv_len + mime_csv.
func parseDialogFilters(blobPtr, blobLen, namePtr, nameLen, extPtr, extLen uintptr) []mygo.FileFilter {
	if blobLen > 0 && blobPtr != 0 {
		b := BytesView(blobPtr, blobLen)
		off := 0
		if off >= len(b) {
			return nil
		}
		n := int(b[off])
		off++
		out := make([]mygo.FileFilter, 0, n)
		for i := 0; i < n && off+2 <= len(b); i++ {
			nl := int(binary.LittleEndian.Uint16(b[off : off+2]))
			off += 2
			if off+nl > len(b) {
				break
			}
			name := string(append([]byte(nil), b[off:off+nl]...))
			off += nl
			if off+2 > len(b) {
				break
			}
			el := int(binary.LittleEndian.Uint16(b[off : off+2]))
			off += 2
			if off+el > len(b) {
				break
			}
			exts := splitCSV(string(b[off : off+el]))
			off += el
			var mimes []string
			if off+2 <= len(b) {
				ml := int(binary.LittleEndian.Uint16(b[off : off+2]))
				off += 2
				if off+ml <= len(b) {
					mimes = splitCSV(string(b[off : off+ml]))
					off += ml
				}
			}
			out = append(out, mygo.FileFilter{Name: name, Extensions: exts, MIMETypes: mimes})
		}
		return out
	}
	if name := CopyString(namePtr, nameLen); name != "" || extLen > 0 {
		return []mygo.FileFilter{{Name: name, Extensions: splitCSV(CopyString(extPtr, extLen))}}
	}
	return nil
}

func hostNotification(sub, a1, a2, a3 uintptr) uintptr {
	switch sub {
	case NotifSupported:
		if mygo.NotificationsSupported() {
			return 1
		}
		return 0

	case NotifShow:
		spec := PtrTo[CNotificationShowSpec](a1)
		if spec == nil {
			SetError(errors.New("zighost: notification show needs spec"))
			return ^uintptr(0)
		}
		opts := mygo.NotificationOptions{
			ID:       CopyString(spec.IDPtr, spec.IDLen),
			Title:    CopyString(spec.TitlePtr, spec.TitleLen),
			Subtitle: CopyString(spec.SubtitlePtr, spec.SubtitleLen),
			Body:     CopyString(spec.BodyPtr, spec.BodyLen),
			Group:    CopyString(spec.GroupPtr, spec.GroupLen),
			Silent:   spec.Silent != 0,
			Image:    CopyBytes(spec.ImagePtr, spec.ImageLen),
		}
		n := mygo.NewNotification(opts)
		if spec.ClickCbID != 0 {
			cbID := spec.ClickCbID
			idCopy := n.ID()
			n.OnClick(func() {
				cs := CStr{}
				ptr, ln := SliceAddr([]byte(idCopy))
				cs.Data, cs.Len = ptr, ln
				activeCall(ZigEventNotification, cbID, 1, uintptrSlicePtr(&cs), 0)
			})
		}
		if err := n.Show(); err != nil {
			SetError(err)
			return ^uintptr(0)
		}
		SetError(nil)
		id := []byte(n.ID())
		return writeBytesToOut(id, a2, a3)

	case NotifClose:
		id := CopyString(a1, a2)
		// Close by creating a handle with the same ID and calling Close,
		// or use Clear on that ID via NewNotification + Close without Show.
		n := mygo.NewNotification(mygo.NotificationOptions{ID: id})
		n.Close()
		return 0

	case NotifClear:
		mygo.ClearNotifications()
		return 0

	case NotifOnAppClick:
		cbID := a1
		mygo.App.OnNotificationClick(func(id string) {
			cs := CStr{}
			ptr, ln := SliceAddr([]byte(id))
			cs.Data, cs.Len = ptr, ln
			activeCall(ZigEventNotification, cbID, 2, uintptrSlicePtr(&cs), 0)
		})
		return 0

	default:
		SetError(errors.New("zighost: unknown notification subop"))
		return ^uintptr(0)
	}
}

